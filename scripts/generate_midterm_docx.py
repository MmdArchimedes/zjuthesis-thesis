def _set_doc_defaults(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Cm(2.54)
    section.bottom_margin = Cm(2.54)
    section.left_margin = Cm(3.17)
    section.right_margin = Cm(3.17)

    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(12)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    pf = normal.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.5
    pf.space_after = Pt(0)
    pf.first_line_indent = Cm(0.74)  # ~2 汉字


def _set_heading_style(doc: Document, style_name: str, east_asia: str, size_pt: int, bold: bool) -> None:
    st = doc.styles[style_name]
    st.font.name = "Times New Roman"
    st.font.size = Pt(size_pt)
    st.font.bold = bold
    st._element.rPr.rFonts.set(qn("w:eastAsia"), east_asia)
    pf = st.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.5
    pf.space_after = Pt(6)
    pf.first_line_indent = Cm(0)


def build() -> Document:
    doc = Document()
    _set_doc_defaults(doc)
    _set_heading_style(doc, "Heading 1", "黑体", 15, True)
    _set_heading_style(doc, "Heading 2", "黑体", 14, True)

    for kind, text in BLOCKS:
        if kind == "title":
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(text)
            run.font.name = "Times New Roman"
            run.font.size = Pt(22)
            run.font.bold = True
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")
            p.paragraph_format.space_after = Pt(12)
            p.paragraph_format.first_line_indent = Cm(0)
        elif kind == "meta":
            p = doc.add_paragraph(text)
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_after = Pt(3)
            for r in p.runs:
                r.font.name = "Times New Roman"
                r.font.size = Pt(12)
                r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
        elif kind == "h1":
            p = doc.add_heading(text, level=1)
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_before = Pt(12)
        elif kind == "h2":
            p = doc.add_heading(text, level=2)
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_before = Pt(6)
        elif kind == "p":
            doc.add_paragraph(text)
        elif kind == "note":
            p = doc.add_paragraph(text)
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_before = Pt(6)
            for r in p.runs:
                r.font.size = Pt(10.5)
                r.italic = True
        else:
            doc.add_paragraph(text)

    return doc


def main() -> None:
    doc = build()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(OUT_PATH))
    print("Wrote:", OUT_PATH)


if __name__ == "__main__":
    main()
